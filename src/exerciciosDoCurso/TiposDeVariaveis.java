package exerciciosDoCurso;

// Crie um programa que declara e imprime variáveis de diferentes tipos (int, double, char, boolean, String).

public class TiposDeVariaveis {
    public static void main(String[] args) {

        String nome = "José";
        int idade = 22;
        double peso = 98.5;
        char genero = 'M';
        boolean ativoNoSistema = true;

        System.out.println("Nome: " + nome);
        System.out.println("Idade: " + idade + " anos");
        System.out.println("Peso: " + peso + "kgs");
        System.out.println("Genero: " + genero);
        System.out.println("Ativo no sistema: " + ativoNoSistema);
    }
}
